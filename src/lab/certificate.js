function makeText(doc, cjk) {
  return function text(str, x, y, opts = {}) {
    const { size = 11, color = INK, width = 400, align = 'left', spacing = 0, height } = opts;
    const body = cjk ? str : String(str).replace(/[^\x20-\x7E]/g, ' ').replace(/\s{2,}/g, ' ').trim() || '-';
    doc.fillColor(color).fontSize(size).font(cjk ? 'cjk' : 'Helvetica');
    doc.text(body, x, y, {
      width,
      align,
      characterSpacing: spacing,
      lineBreak: true,
      height,
      ellipsis: true,
    });
  };
}

function draw(doc, record, story) {
  const font = resolveFont();
  let cjk = font.cjk;
  if (cjk) {
    try {
      doc.registerFont('cjk', font.path, font.family || undefined);
    } catch (err) {
      console.warn('[pdf] 中文字体注册失败，降级英文排版:', err.message);
      cjk = false;
    }
  }
  const L = labels(cjk);
  const t = makeText(doc, cjk);

  const W = doc.page.width;
  const H = doc.page.height;
  const X = 56;
  const CW = W - X * 2;

  // 顶部色带（扁平化：纯色矩形）
  const bw = W / BANDS.length;
  BANDS.forEach((c, i) => doc.rect(i * bw, 0, Math.ceil(bw), 14).fill(c));

  // 双线边框
  doc.roundedRect(24, 26, W - 48, H - 52, 16).lineWidth(1.5).strokeColor('#e2e2ea').stroke();
  doc.roundedRect(32, 34, W - 64, H - 68, 12).lineWidth(0.8).strokeColor('#f0f0f4').stroke();

  // 头部
  t(L.kicker, X, 58, { size: 9, color: MUTED, width: CW, align: 'center', spacing: 2.2 });
  t(L.title, X, 80, { size: 31, color: INK, width: CW, align: 'center' });
  t(L.subtitle, X, 124, { size: 11, color: '#6d6d78', width: CW, align: 'center' });
  doc.rect(W / 2 - 45, 154, 90, 4).fill(ACCENT);

  // 编号 / 日期
  t(`${L.certNo}  ${record.id}`, X, 182, { size: 9.5, color: MUTED, width: 260, spacing: 0.8 });
  t(
    `${L.issued}  ${fmtDate(record.createdAt)}    ${L.source}  ${String(record.source || 'web').toUpperCase()}`,
    W - X - 240,
    182,
    { size: 9.5, color: MUTED, width: 240, align: 'right', spacing: 0.8 }
  );

  // 作品卡片
  doc.roundedRect(X, 208, CW, 112, 14).fill(PAPER);
  doc.rect(X, 208, 6, 112).fill(ACCENT);
  t(L.works, X + 26, 224, { size: 8.5, color: MUTED, width: 100, spacing: 1.6 });
  t(record.storyTitle || story?.title || '-', X + 26, 240, { size: 20, color: INK, width: CW - 60, height: 30 });
  const castNames = (record.castNames || []).join(' · ') || '-';
  t(
    `${L.meta} ${castNames}    |    ${record.scenes || 0} ${L.scenes}    |    ${record.chars || 0} ${L.chars}`,
    X + 26,
    277,
    { size: 10, color: '#5f5f6a', width: CW - 60 }
  );
  t(`sha256 ${String(record.fingerprint || '').slice(0, 16)} · wayhug-lab/1.0`, X + 26, 295, {
    size: 8.5,
    color: '#a0a0aa',
    width: CW - 60,
  });

  // 持有人
  t(L.holder, X, 348, { size: 8.5, color: MUTED, width: 200, spacing: 1.6 });
  t(record.name || '-', X, 364, { size: 17, color: INK, width: 240, height: 24 });
  t(`${L.email}  ${record.email || '-'}`, X, 393, { size: 10, color: '#5f5f6a', width: 300 });
  t(L.expiry, W - X - 220, 348, { size: 8.5, color: MUTED, width: 220, align: 'right', spacing: 1.6 });
  t(fmtDate(record.expiresAt), W - X - 220, 364, { size: 13, color: INK, width: 220, align: 'right' });

  // 授权范围
  const boxY = 430;
  const boxH = 218;
  doc.roundedRect(X, boxY, CW, boxH, 14).lineWidth(1).strokeColor(LINE).fillAndStroke('#ffffff', LINE);
  doc.rect(X, boxY, 6, boxH).fill('#2f9e77');
  t(L.scope, X + 26, boxY + 18, { size: 9.5, color: '#2f9e77', width: 220, spacing: 1.8 });
  L.bullets.forEach((line, i) => {
    doc.circle(X + 32, boxY + 53 + i * 30 + 4, 3).fill(ACCENT);
    t(line, X + 46, boxY + 46 + i * 30, { size: 11, color: '#3c3c46', width: CW - 80, height: 26 });
  });

  // 校验信息
  t(L.verify, X, 674, { size: 8.5, color: MUTED, width: 100, spacing: 1.6 });
  t(`${labConfig.siteUrl}${labConfig.basePath}/verify/${record.id}`, X, 689, { size: 10, color: '#3c3c46', width: CW });
  t(L.fingerprint, X, 711, { size: 8.5, color: MUTED, width: 100, spacing: 1.6 });
  t(`sha256:${record.fingerprint || '-'}`, X, 726, { size: 9.5, color: '#3c3c46', width: CW });

  // 签名与扁平化印章
  doc.lineWidth(1).strokeColor('#c9c9d4').moveTo(X, 760).lineTo(X + 190, 760).stroke();
  t(L.signer, X, 767, { size: 10.5, color: '#3c3c46', width: 240 });

  doc.roundedRect(W - 176, 682, 104, 104, 10).lineWidth(2).strokeColor(ACCENT).stroke();
  t('IP', W - 176, 708, { size: 27, color: ACCENT, width: 104, align: 'center' });
  t('WAYHUG · LAB', W - 176, 746, { size: 7, color: MUTED, width: 104, align: 'center', spacing: 1.2 });
  t(fmtDate(record.createdAt), W - 176, 758, { size: 7, color: '#b0b0ba', width: 104, align: 'center' });

  t(L.footer, X, 798, { size: 8.5, color: '#a8a8b2', width: CW, align: 'center' });
  BANDS.forEach((c, i) => doc.rect(i * bw, H - 14, Math.ceil(bw), 14).fill(c));
}

/** 生成证书 Buffer（邮件附件用） */
export function certificateBuffer(record, story) {
  const doc = new PDFDocument({
    size: 'A4',
    margin: 0,
    info: {
      Title: `IP Experience Certificate ${record.id}`,
      Author: 'Wayhug Lab',
      Subject: record.storyTitle || '',
      Creator: 'wayhug.com lab',
      Producer: 'wayhug.com lab',
    },
  });
  const chunks = [];
  const done = new Promise((resolve, reject) => {
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });
  draw(doc, record, story);
  doc.end();
  return done;
}

/** 直接写入 HTTP 响应 */
export async function streamCertificate(record, story, res) {
  const buf = await certificateBuffer(record, story);
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `inline; filename="wayhug-ip-${record.id}.pdf"; filename*=UTF-8''${encodeURIComponent(`Wayhug_IP体验权_${record.id}.pdf`)}`
  );
  res.setHeader('Content-Length', buf.length);
  res.end(buf);
}
